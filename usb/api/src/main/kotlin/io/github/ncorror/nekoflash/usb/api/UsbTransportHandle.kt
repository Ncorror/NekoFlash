package io.github.ncorror.nekoflash.usb.api

/**
 * Удерживаемый интерфейс устройства.
 *
 * Ресурс принадлежит той `SessionGeneration`, в которой был получен. После
 * [close] handle непригоден и не «оживает»: следующий захват выдаёт новый.
 *
 * Ввода-вывода здесь пока нет. Он появится вместе с протокольными движками,
 * которые и будут владеть транспортом; сейчас handle нужен, чтобы захват можно
 * было проверить на устройстве и корректно освободить.
 */
public interface UsbTransportHandle : AutoCloseable {
    /** Интерфейс, который удерживается. */
    public val candidate: UsbInterfaceCandidate

    /** Удерживается ли интерфейс прямо сейчас. */
    public val held: Boolean

    /**
     * Освобождает интерфейс и закрывает соединение.
     *
     * Повторный вызов безопасен: освобождение уже освобождённого ресурса — не
     * ошибка, а обычный исход гонки с отключением устройства.
     */
    override fun close()
}

/** Почему интерфейс не удалось захватить. */
public enum class UsbClaimFailure {
    /** Устройство исчезло между обнаружением и захватом. */
    DEVICE_GONE,

    /**
     * Платформа отказалась открыть соединение.
     *
     * Обычно означает отсутствие разрешения на момент вызова: оно могло быть
     * отозвано после выдачи.
     */
    OPEN_REFUSED,

    /**
     * Платформа отказалась отдать интерфейс.
     *
     * Отказ принадлежит устройству и системе, а не приложению, и показывается
     * как есть.
     */
    INTERFACE_REFUSED,
}

/** Результат попытки захватить интерфейс. */
public sealed interface UsbClaimResult {
    /** Интерфейс захвачен; владение переходит вызывающему вместе с [handle]. */
    public data class Claimed(val handle: UsbTransportHandle) : UsbClaimResult

    /** Захват не состоялся. */
    public data class Failed(val reason: UsbClaimFailure) : UsbClaimResult
}
