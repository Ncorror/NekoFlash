package io.github.ncorror.nekoflash.usb.api

/**
 * Удерживаемый интерфейс устройства.
 *
 * Ресурс принадлежит той `SessionGeneration`, в которой был получен. После
 * [close] handle непригоден и не «оживает»: следующий захват выдаёт новый.
 *
 * Ввод-вывод здесь сырой и синхронный: пара bulk-эндпоинтов и ничего больше.
 * Рамки протокола, повторы и разбор пакетов сюда не спускаются — этим владеют
 * протокольные движки. Владелец транспорта обязан сериализовать запись сам:
 * приём и передача идут по разным эндпоинтам и могут выполняться одновременно,
 * но два одновременных отправителя перемешают один поток.
 */
public interface UsbTransportHandle : AutoCloseable {
    /** Интерфейс, который удерживается. */
    public val candidate: UsbInterfaceCandidate

    /** Удерживается ли интерфейс прямо сейчас. */
    public val held: Boolean

    /**
     * Принимает данные от устройства одной передачей.
     *
     * Ровно одна операция приёма — и никакого дочитывания остатка следующим
     * вызовом. Это не деталь реализации, а перенесённый инвариант: в A2
     * дробление одного объявленного ADB-payload на несколько меньших приёмов
     * детерминированно рвало передачу после 32768 байт и уносило транспорт
     * целиком. Разбор — `reference/archives/NekoFlash-A2-frozen.zip`,
     * `docs/ADB_INBOUND_USB_FRAMING.md`.
     *
     * Вызывающий сам решает, что означает результат короче запрошенного:
     * контракт сообщает число перенесённых байт и не судит о рамке.
     *
     * @throws IllegalArgumentException если окно передачи или таймаут заданы
     * неверно — это ошибка программиста, а не исход обмена.
     */
    public fun receive(
        destination: ByteArray,
        offset: Int,
        length: Int,
        timeoutMillis: Int,
    ): UsbTransferResult

    /**
     * Передаёт данные устройству одной передачей.
     *
     * Повтора здесь нет намеренно. Повторная отправка после неоднозначной
     * записи запрещена, пока нельзя доказать, что предыдущая попытка не
     * мутировала peer (`docs/03_PROTOCOL_AND_SAFETY_INVARIANTS_RU.md` §3), а
     * доказательство этого принадлежит протокольному слою, а не транспорту.
     *
     * @throws IllegalArgumentException если окно передачи или таймаут заданы
     * неверно.
     */
    public fun send(
        source: ByteArray,
        offset: Int,
        length: Int,
        timeoutMillis: Int,
    ): UsbTransferResult

    /**
     * Освобождает интерфейс и закрывает соединение.
     *
     * Повторный вызов безопасен: освобождение уже освобождённого ресурса — не
     * ошибка, а обычный исход гонки с отключением устройства.
     */
    override fun close()
}

/** Почему интерфейс не удалось захватить. */
public enum class UsbClaimFailure {
    /** Устройство исчезло между обнаружением и захватом. */
    DEVICE_GONE,

    /**
     * Платформа отказалась открыть соединение.
     *
     * Обычно означает отсутствие разрешения на момент вызова: оно могло быть
     * отозвано после выдачи.
     */
    OPEN_REFUSED,

    /**
     * Платформа отказалась отдать интерфейс.
     *
     * Отказ принадлежит устройству и системе, а не приложению, и показывается
     * как есть.
     */
    INTERFACE_REFUSED,

    /**
     * Интерфейс есть, но объявленной им пары bulk-эндпоинтов в нём больше нет.
     *
     * Означает, что дескриптор, по которому был выбран кандидат, устарел:
     * устройство успело переподключиться или сменить конфигурацию. Отдельная
     * причина нужна, чтобы не выдавать это за отказ платформы: платформа ни в
     * чём не отказывала.
     */
    ENDPOINTS_MISSING,
}

/** Результат попытки захватить интерфейс. */
public sealed interface UsbClaimResult {
    /** Интерфейс захвачен; владение переходит вызывающему вместе с [handle]. */
    public data class Claimed(val handle: UsbTransportHandle) : UsbClaimResult

    /** Захват не состоялся. */
    public data class Failed(val reason: UsbClaimFailure) : UsbClaimResult
}
